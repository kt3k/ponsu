// Monoid tables are flat arrays t with t[x * n + y] = x·y, and element 0 is the identity.

export function permutations(arr) {
  if (arr.length <= 1) return [arr.slice()];
  const out = [];
  arr.forEach((x, i) => {
    const rest = arr.slice(0, i).concat(arr.slice(i + 1));
    for (const p of permutations(rest)) out.push([x, ...p]);
  });
  return out;
}

// Permutations of the elements that fix the identity 0
export function identityFixingPerms(n) {
  return permutations([...Array(n - 1)].map((_, i) => i + 1)).map((p) => [0, ...p]);
}

// perm maps old label -> new label
function relabel(t, n, perm) {
  const r = new Array(n * n);
  for (let x = 0; x < n; x++)
    for (let y = 0; y < n; y++) r[perm[x] * n + perm[y]] = perm[t[x * n + y]];
  return r;
}

export function canonical(t, n, perms) {
  let best = null;
  for (const p of perms) {
    const s = relabel(t, n, p).join("");
    if (best === null || s < best) best = s;
  }
  return best;
}

export function transpose(t, n) {
  const r = new Array(n * n);
  for (let x = 0; x < n; x++) for (let y = 0; y < n; y++) r[y * n + x] = t[x * n + y];
  return r;
}

// All monoids of order n up to isomorphism, as canonical table strings.
// Backtracking over the (n-1)×(n-1) block of non-identity products, pruning
// as soon as a fully defined associativity instance fails.
export function enumerateTables(n) {
  const perms = identityFixingPerms(n);
  const t = new Array(n * n).fill(-1);
  for (let x = 0; x < n; x++) {
    t[x] = x;
    t[x * n] = x;
  }
  const cells = [];
  for (let x = 1; x < n; x++) for (let y = 1; y < n; y++) cells.push(x * n + y);

  const consistent = () => {
    for (let x = 1; x < n; x++)
      for (let y = 1; y < n; y++) {
        const xy = t[x * n + y];
        if (xy < 0) continue;
        for (let z = 1; z < n; z++) {
          const yz = t[y * n + z];
          if (yz < 0) continue;
          const l = t[xy * n + z];
          const r = t[x * n + yz];
          if (l >= 0 && r >= 0 && l !== r) return false;
        }
      }
    return true;
  };

  const seen = new Set();
  const go = (i) => {
    if (i === cells.length) {
      seen.add(canonical(t, n, perms));
      return;
    }
    for (let v = 0; v < n; v++) {
      t[cells[i]] = v;
      if (consistent()) go(i + 1);
    }
    t[cells[i]] = -1;
  };
  go(0);
  return [...seen];
}

// Structural properties of a monoid table
export function analyze(t, n) {
  const op = (x, y) => t[x * n + y];
  const els = [...Array(n).keys()];
  const commutative = els.every((x) => els.every((y) => op(x, y) === op(y, x)));
  const idempotents = els.filter((x) => op(x, x) === x);
  const units = els.filter((x) => els.some((y) => op(x, y) === 0 && op(y, x) === 0));
  const zero = els.find((z) => els.every((x) => op(z, x) === z && op(x, z) === z));
  const leftCancel = els.every((a) => new Set(els.map((x) => op(a, x))).size === n);
  const rightCancel = els.every((a) => new Set(els.map((x) => op(x, a))).size === n);
  const isGroup = units.length === n;
  const isBand = idempotents.length === n;
  // Monogenic: generated by a single element
  const generated = (g) => {
    const s = new Set([0]);
    let x = g;
    while (!s.has(x)) {
      s.add(x);
      x = op(x, g);
    }
    return s;
  };
  const cyclic = els.some((g) => generated(g).size === n);
  // Inverse monoid: every x has exactly one y with x·y·x = x and y·x·y = y
  const inverse = els.every((x) => els.filter((y) => op(op(x, y), x) === x && op(op(y, x), y) === y).length === 1);
  return { commutative, idempotents, units, zero, leftCancel, rightCancel, isGroup, isBand, cyclic, inverse };
}

export function tags(m) {
  const tags = [];
  if (m.isGroup) tags.push("group");
  if (m.commutative) tags.push("commutative");
  if (m.isBand) tags.push("band");
  if (m.zero !== undefined && m.n > 1) tags.push("zero");
  if (m.cyclic) tags.push("cyclic");
  if (m.inverse && !m.isGroup) tags.push("inverse");
  if (!m.isGroup && m.leftCancel !== m.rightCancel) tags.push(m.leftCancel ? "leftCancel" : "rightCancel");
  if (m.selfDual) tags.push("selfDual");
  return tags;
}

export const sortKey = (m, key) =>
  [m.isGroup ? 0 : 1, m.commutative ? 0 : 1, String(9 - m.units.length), String(9 - m.idempotents.length), key].join("|");

// Smallest set of non-identity elements that generates the monoid (first one in subset order)
export function minimalGenerators(t, n) {
  const closure = (gens) => {
    const seen = new Set([0]);
    const queue = [0];
    while (queue.length) {
      const x = queue.pop();
      for (const g of gens) {
        const y = t[x * n + g];
        if (!seen.has(y)) seen.add(y), queue.push(y);
      }
    }
    return seen.size;
  };
  const others = [...Array(n - 1)].map((_, i) => i + 1);
  for (let k = 0; k <= others.length; k++) {
    const pick = (start, acc) => {
      if (acc.length === k) return closure(acc) === n ? acc : null;
      for (let i = start; i < others.length; i++) {
        const found = pick(i + 1, [...acc, others[i]]);
        if (found) return found;
      }
      return null;
    };
    const found = pick(0, []);
    if (found) return found;
  }
  return others;
}

// Green's relations. Returns the D-classes (= J-classes, as M is finite), each with its
// R-classes as rows, L-classes as columns and H-classes as cells, plus the J-order between them.
export function greenStructure(t, n) {
  const els = [...Array(n).keys()];
  const op = (x, y) => t[x * n + y];
  const ideal = (f) => [...new Set(els.flatMap(f))].sort((a, b) => a - b);
  const R = els.map((x) => ideal((m) => [op(x, m)]));
  const L = els.map((x) => ideal((m) => [op(m, x)]));
  const J = els.map((x) => ideal((m) => els.map((k) => op(op(m, x), k))));
  const groupBy = (keyOf, xs) => {
    const map = new Map();
    for (const x of xs) {
      const k = keyOf(x);
      map.set(k, [...(map.get(k) ?? []), x]);
    }
    return [...map.values()];
  };
  const idempotent = (x) => op(x, x) === x;
  const classes = groupBy((x) => J[x].join(), els).map((d) => {
    const rows = groupBy((x) => R[x].join(), d);
    const cols = groupBy((x) => L[x].join(), d);
    const cells = rows.map((r) => cols.map((c) => r.filter((x) => c.includes(x))));
    return {
      elements: d,
      ideal: J[d[0]],
      cells,
      group: cells.map((row) => row.map((h) => h.some(idempotent))),
      idempotents: d.filter(idempotent),
    };
  });
  // Top of the J-order first: larger ideals above smaller ones
  classes.sort((a, b) => b.ideal.length - a.ideal.length || a.elements[0] - b.elements[0]);
  const below = (a, b) => a !== b && a.ideal.every((x) => b.ideal.includes(x));
  // Hasse diagram covers, and a layer index = length of the longest chain from the top
  const covers = [];
  classes.forEach((a, i) =>
    classes.forEach((b, j) => {
      if (below(b, a) && !classes.some((c) => below(c, a) && below(b, c))) covers.push([i, j]);
    }),
  );
  const layer = classes.map(() => 0);
  for (let changed = true; changed; ) {
    changed = false;
    for (const [i, j] of covers)
      if (layer[j] < layer[i] + 1) {
        layer[j] = layer[i] + 1;
        changed = true;
      }
  }
  return { classes, covers, layer };
}
