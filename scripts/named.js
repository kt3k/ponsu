// Well-known monoids, built from their definitions. Each entry is [order, table, name];
// element 0 is the identity, and products are written left to right (x·y = "x then y"),
// matching the right action s ↦ s·x of the switches on the site.

function fromOp(n, op) {
  const t = new Array(n * n);
  for (let x = 0; x < n; x++) for (let y = 0; y < n; y++) t[x * n + y] = op(x, y);
  return t;
}

const sub = (k) => String(k).replace(/\d/g, (d) => "₀₁₂₃₄₅₆₇₈₉"[d]);
const sup = (k) => String(k).replace(/\d/g, (d) => "⁰¹²³⁴⁵⁶⁷⁸⁹"[d]);

const cyclicGroup = (n) => fromOp(n, (x, y) => (x + y) % n);
// <g | g^(i+p) = g^i>, elements g^0 .. g^(i+p-1)
const monogenic = (i, p) => fromOp(i + p, (x, y) => (x + y < i + p ? x + y : i + ((x + y - i) % p)));
// Chain semilattice 1 > ... > 0 under meet
const chain = (n) => fromOp(n, (x, y) => Math.max(x, y));
const product = (a, na, b, nb) =>
  fromOp(na * nb, (x, y) => a[Math.floor(x / nb) * na + Math.floor(y / nb)] * nb + b[(x % nb) * nb + (y % nb)]);
const withZero = (t, n) => fromOp(n + 1, (x, y) => (x === n || y === n ? n : t[x * n + y]));
// S¹: adjoin an identity to a semigroup S of order k given by sop on 0..k-1
const withIdentity = (k, sop) => fromOp(k + 1, (x, y) => (x === 0 ? y : y === 0 ? x : 1 + sop(x - 1, y - 1)));

// Monoid of transformations generated by gens (arrays over 0..m-1), composed "x then y".
// With all = true, gens is taken as the full element list instead.
function transformationMonoid(m, gens, all = false) {
  const id = [...Array(m).keys()];
  const key = (f) => f.join(",");
  const els = [id];
  const index = new Map([[key(id), 0]]);
  const push = (f) => {
    if (!index.has(key(f))) {
      index.set(key(f), els.length);
      els.push(f);
    }
  };
  if (all) gens.forEach(push);
  for (let i = 0; i < els.length; i++)
    for (const g of all ? [] : gens) push(els[i].map((v) => g[v]));
  const n = els.length;
  return [n, fromOp(n, (x, y) => index.get(key(els[x].map((v) => els[y][v]))))];
}

const allMaps = (m) => {
  const out = [];
  const go = (f) => (f.length === m ? out.push(f) : [...Array(m).keys()].forEach((v) => go([...f, v])));
  go([]);
  return out;
};

// Rees 0-matrix semigroup over the trivial group with sandwich matrix p[j][k], plus identity.
// Elements: 1, 0, then (i, j) pairs.
function reesWithIdentity(p) {
  const I = p[0].length;
  const J = p.length;
  const pair = (x) => [Math.floor((x - 2) / J), (x - 2) % J];
  const n = 2 + I * J;
  return [
    n,
    fromOp(n, (x, y) => {
      if (x === 0) return y;
      if (y === 0) return x;
      if (x === 1 || y === 1) return 1;
      const [i, j] = pair(x);
      const [k, l] = pair(y);
      return p[j][k] ? 2 + i * J + l : 1;
    }),
  ];
}

export function namedConstructions() {
  const out = [];
  const add = (n, table, name) => out.push([n, table, name]);

  // Groups
  for (let k = 2; k <= 6; k++) add(k, cyclicGroup(k), `Z${sub(k)}`);
  add(4, product(cyclicGroup(2), 2, cyclicGroup(2), 2), "Z₂×Z₂ (Klein)");
  const perms3 = [[0, 1, 2], [1, 0, 2], [0, 2, 1], [1, 2, 0], [2, 0, 1], [2, 1, 0]];
  add(...transformationMonoid(3, perms3, true), "S₃");

  // Groups with a zero adjoined
  for (let k = 2; k <= 5; k++) add(k + 1, withZero(cyclicGroup(k), k), `Z${sub(k)}⁰`);
  add(5, withZero(product(cyclicGroup(2), 2, cyclicGroup(2), 2), 4), "(Z₂×Z₂)⁰");

  // Semilattices
  add(2, chain(2), "U₁ = {1, 0}");
  for (let k = 3; k <= 6; k++) add(k, chain(k), `C${sub(k)} (chain)`);
  add(4, product(chain(2), 2, chain(2), 2), "U₁×U₁");

  // Small direct products
  const order2 = [[cyclicGroup(2), "Z₂"], [chain(2), "U₁"]];
  const order3 = [
    [cyclicGroup(3), "Z₃"],
    [withZero(cyclicGroup(2), 2), "Z₂⁰"],
    [chain(3), "C₃"],
    [withIdentity(2, (x, y) => y), "R₂¹"],
    [withIdentity(2, (x) => x), "L₂¹"],
  ];
  add(4, product(cyclicGroup(2), 2, chain(2), 2), "Z₂×U₁");
  for (const [a, an] of order2) for (const [b, bn] of order3) if (!(an === "Z₂" && bn === "Z₃")) add(6, product(a, 2, b, 3), `${an}×${bn}`);

  // Left / right zero and null semigroups with an identity
  add(3, withIdentity(2, (x, y) => y), "R₂¹ = U₂ (flip-flop)");
  for (let k = 2; k <= 5; k++) {
    if (k > 2) add(k + 1, withIdentity(k, (x, y) => y), `R${sub(k)}¹`);
    add(k + 1, withIdentity(k, (x) => x), `L${sub(k)}¹`);
    if (k > 2) add(k + 1, withIdentity(k, () => 0), `O${sub(k)}¹ (null)`);
  }
  // 2×2 rectangular band with an identity
  add(5, withIdentity(4, (x, y) => (x & 2) | (y & 1)), "(2×2 rectangular band)¹");

  // Monogenic monoids
  for (let n = 2; n <= 6; n++) for (let i = 1; i < n; i++) add(n, monogenic(i, n - i), `⟨g | g${sup(n)} = g${i === 1 ? "" : sup(i)}⟩`);

  // Transformation monoids
  add(...transformationMonoid(2, allMaps(2), true), "T₂ (full transformation monoid)");
  const orderPreserving = (m) => allMaps(m).filter((f) => f.every((v, i) => i === 0 || f[i - 1] <= v));
  add(...transformationMonoid(3, orderPreserving(3).filter((f) => f.every((v, i) => v >= i)), true), "Cat₃ (Catalan monoid)");

  // Rees matrix constructions
  add(...reesWithIdentity([[1, 0], [0, 1]]), "B₂¹ (Brandt monoid)");
  add(...reesWithIdentity([[1, 1], [0, 1]]), "A₂¹");

  return out;
}

